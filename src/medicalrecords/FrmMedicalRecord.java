    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String consultationReason =
            txtConsultationReason.getText().trim();

    String diagnosis =
            txtDiagnosis.getText().trim();

    String treatment =
            txtTreatment.getText().trim();

    String notes =
            txtNotes.getText().trim();

    if (consultationReason.isEmpty()
            || diagnosis.isEmpty()
            || treatment.isEmpty()) {

        showError(
                "Debe completar el motivo de consulta, "
                + "el diagnóstico y el tratamiento"
        );

        return;
    }
    
    boolean saved = controller.addMedicalRecord(
            consultationReason,
            diagnosis,
            treatment,
            notes
    );

    if (saved) {
        clear();
    }
    }//GEN-LAST:event_btnSaveActionPerformed

