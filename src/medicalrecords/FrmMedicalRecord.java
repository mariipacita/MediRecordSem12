    @Override
    public void showData(MedicalRecord data) {
    if (data == null) {
        return;
    }

    jDateChooser1.setDate(
            java.sql.Date.valueOf(data.getDate())
    );

    txtConsultationReason.setText(
            data.getConsultationReason()
    );

    txtDiagnosis.setText(data.getDiagnosis());
    txtTreatment.setText(data.getTreatment());
    txtNotes.setText(data.getNotes());
}
